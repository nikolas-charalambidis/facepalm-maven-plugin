package dev.nichar.facepalm;

import static org.assertj.core.api.Assertions.assertThat;

import dev.nichar.facepalm.engine.ScoringStrategy;
import java.io.IOException;
import java.io.PrintWriter;
import java.io.StringWriter;
import java.nio.charset.StandardCharsets;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.util.regex.Pattern;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;
import picocli.CommandLine;

/**
 * Options, defaults and exit codes of {@link FacepalmCLI} (#235).
 *
 * @see <a href=
 * "https://github.com/nikolas-charalambidis/facepalm-maven-plugin/blob/master/docs/requirements.md#fr-06">FR-06</a>
 * @see <a href=
 * "https://github.com/nikolas-charalambidis/facepalm-maven-plugin/blob/master/docs/requirements.md#fr-08">FR-08</a>
 */
class FacepalmCLITest {

    /**
     * Fixture projects of the integration tests, scanned here without Maven.
     */
    private static final Path FIXTURES = Paths.get("src/test/resources-its/dev/nichar/facepalm/FacepalmMojoIT");

    /**
     * Content of the plugin descriptor generated by maven-plugin-plugin before the test phase.
     */
    private static String descriptor;

    @BeforeAll
    static void readDescriptor() throws IOException {
        try (var in = FacepalmCLITest.class.getClassLoader().getResourceAsStream("META-INF/maven/plugin.xml")) {
            assertThat(in).as("plugin descriptor not generated").isNotNull();
            descriptor = new String(in.readAllBytes(), StandardCharsets.UTF_8);
        }
    }

    @Test
    void clean_directory_exits_with_0(@TempDir final Path output) {
        final var result = execute("--output", output.toString(), FIXTURES.resolve("clean_project").toString());

        assertThat(result.exitCode()).isEqualTo(FacepalmCLI.EXIT_OK);
        assertThat(output.resolve("facepalm-findings.json")).isRegularFile();
    }

    @Test
    void critical_finding_exits_with_1(@TempDir final Path output) {
        final var result = execute("--output", output.toString(), FIXTURES.resolve("private_key_project").toString());

        assertThat(result.exitCode()).isEqualTo(FacepalmCLI.EXIT_FINDINGS);
        assertThat(result.err()).isEmpty();
    }

    /**
     * The dirty fixture has a WARNING only: it passes by default and fails with {@code --fail-on-warnings}, like
     * {@code failOnWarnings} in Maven.
     */
    @Test
    void warning_fails_only_with_fail_on_warnings(@TempDir final Path output) {
        final var dirty = FIXTURES.resolve("dirty_project").toString();

        assertThat(execute("--output", output.toString(), dirty).exitCode()).isEqualTo(FacepalmCLI.EXIT_OK);
        assertThat(execute("--fail-on-warnings", "--output", output.toString(), dirty).exitCode())
            .isEqualTo(FacepalmCLI.EXIT_FINDINGS);
    }

    @Test
    void critical_finding_passes_with_fail_on_error_false(@TempDir final Path output) {
        final var result = execute("--fail-on-error=false", "--output", output.toString(),
            FIXTURES.resolve("private_key_project").toString());

        assertThat(result.exitCode()).isEqualTo(FacepalmCLI.EXIT_OK);
    }

    @Test
    void invalid_arguments_exit_with_2() {
        assertThat(execute("--verbose").exitCode()).isEqualTo(FacepalmCLI.EXIT_ERROR);
        assertThat(execute("--output").exitCode()).isEqualTo(FacepalmCLI.EXIT_ERROR);
        assertThat(execute("a", "b").exitCode()).isEqualTo(FacepalmCLI.EXIT_ERROR);
        final var result = execute("--error-threshold", "high");
        assertThat(result.exitCode()).isEqualTo(FacepalmCLI.EXIT_ERROR);
        assertThat(result.err()).contains("--error-threshold").contains("Usage: facepalm");
    }

    @Test
    void scan_that_cannot_run_exits_with_2_without_stack_trace(@TempDir final Path output) {
        final var result = execute("--skip-binary-regex", "(", "--output", output.toString(),
            FIXTURES.resolve("clean_project").toString());

        assertThat(result.exitCode()).isEqualTo(FacepalmCLI.EXIT_ERROR);
        assertThat(result.err()).startsWith("Facepalm scan failed: ").doesNotContain("\tat ");
    }

    @Test
    void debug_prints_the_stack_trace(@TempDir final Path output) {
        final var result = execute("--debug", "--skip-binary-regex", "(", "--output", output.toString(),
            FIXTURES.resolve("clean_project").toString());

        assertThat(result.exitCode()).isEqualTo(FacepalmCLI.EXIT_ERROR);
        assertThat(result.err()).contains("java.util.regex.PatternSyntaxException").contains("\tat ");
    }

    @Test
    void help_and_version_exit_with_0() {
        final var help = execute("--help");
        assertThat(help.exitCode()).isEqualTo(FacepalmCLI.EXIT_OK);
        assertThat(help.out()).contains("Usage: facepalm", "--fail-on-warnings", "Exit codes:");

        final var version = execute("--version");
        assertThat(version.exitCode()).isEqualTo(FacepalmCLI.EXIT_OK);
        assertThat(version.out().strip()).isEqualTo("facepalm " + FacepalmCLI.version());
    }

    /**
     * The version comes from a resource filtered when Maven processes the resources, so it is known in tests and IDE
     * runs too, not only in the packaged jar.
     */
    @Test
    void version_is_read_from_the_filtered_resource() {
        assertThat(FacepalmCLI.version()).matches("\\d+\\.\\d+\\.\\d+(-SNAPSHOT)?");
    }

    @Test
    void directory_and_output_default_to_the_current_directory_and_its_target() {
        final var cli = parse();

        final var cwd = Paths.get(".").toAbsolutePath().normalize();
        assertThat(cli.root()).isEqualTo(cwd);
        assertThat(cli.output()).isEqualTo(cwd.resolve("target"));
        assertThat(parse("some/project").output())
            .isEqualTo(Paths.get("some/project").toAbsolutePath().normalize().resolve("target"));
    }

    /**
     * Without options, the CLI uses the documented defaults of the Maven goal, read from its plugin descriptor (#70).
     */
    @Test
    void defaults_match_the_maven_goal() {
        final var config = parse().config();
        final var engine = config.getEngine();
        final var scoring = config.getScoring();

        assertThat(String.valueOf(engine.getMaxFileSizeBytes())).isEqualTo(mojoDefault("maxFileSizeBytes"));
        assertThat(engine.getSkipBinaryRegex()).isEqualTo(mojoDefault("skipBinaryRegex"));
        assertThat(String.valueOf(engine.isShowProcessed())).isEqualTo(mojoDefault("showProcessed"));
        assertThat(String.valueOf(engine.isShowSkipped())).isEqualTo(mojoDefault("showSkipped"));
        assertThat(String.valueOf(engine.isSuppressions())).isEqualTo(mojoDefault("suppressions"));
        assertThat(scoring.getStrategy().name()).isEqualTo(mojoDefault("scoringStrategy"));
        assertThat(String.valueOf(scoring.getErrorThreshold())).isEqualTo(mojoDefault("errorThreshold"));
        assertThat(String.valueOf(scoring.getWarningThreshold())).isEqualTo(mojoDefault("warningThreshold"));
        assertThat(String.valueOf(scoring.isShowScoring())).isEqualTo(mojoDefault("showScoring"));
        assertThat(String.valueOf(scoring.isShowDetails())).isEqualTo(mojoDefault("showDetails"));
        assertThat(String.valueOf(scoring.isFailOnError())).isEqualTo(mojoDefault("failOnError"));
        assertThat(String.valueOf(scoring.isFailOnWarnings())).isEqualTo(mojoDefault("failOnWarnings"));
        // Not set, as in Maven: the CPU count, the default skip directories, and no useDefaultSkipDirs.
        assertThat(engine.getThreads()).isEqualTo(Runtime.getRuntime().availableProcessors());
        assertThat(engine.getUseDefaultSkipDirs()).isNull();
        assertThat(engine.isSkipDirsReplacingDefaults()).isFalse();
    }

    @Test
    void options_map_to_the_configuration() {
        final var config = parse("--threads", "3", "--max-file-size-bytes", "1024", "--skip-binary-regex", ".*\\.bin",
            "--skip-dirs", " logs, tmp,,logs ", "--use-default-skip-dirs", "--show-scoring", "--show-details=true",
            "--suppressions=false", "--scoring-strategy", "average", "--error-threshold", "90",
            "--warning-threshold", "50", "--fail-on-error=false", "--fail-on-warnings").config();
        final var engine = config.getEngine();
        final var scoring = config.getScoring();

        assertThat(engine.getThreads()).isEqualTo(3);
        assertThat(engine.getMaxFileSizeBytes()).isEqualTo(1024);
        assertThat(engine.getSkipBinaryRegex()).isEqualTo(".*\\.bin");
        // Comma-separated like -DskipDirs in Maven: stripped, without blanks and duplicates.
        assertThat(engine.getUseDefaultSkipDirs()).isTrue();
        assertThat(engine.getSkipDirs()).contains("logs", "tmp", ".git").doesNotContain("", " logs");
        assertThat(engine.isSuppressions()).isFalse();
        assertThat(scoring.getStrategy()).isEqualTo(ScoringStrategy.AVERAGE);
        assertThat(scoring.getErrorThreshold()).isEqualTo(90);
        assertThat(scoring.getWarningThreshold()).isEqualTo(50);
        assertThat(scoring.isShowScoring()).isTrue();
        assertThat(scoring.isShowDetails()).isTrue();
        assertThat(scoring.isFailOnError()).isFalse();
        assertThat(scoring.isFailOnWarnings()).isTrue();
    }

    @Test
    void skip_dirs_without_use_default_skip_dirs_replaces_the_defaults_as_in_maven() {
        final var engine = parse("--skip-dirs", "logs").config().getEngine();

        assertThat(engine.getSkipDirs()).containsExactly("logs");
        assertThat(engine.isSkipDirsReplacingDefaults()).isTrue();
    }

    @Test
    void debug_lists_processed_and_skipped_files() {
        final var engine = parse("--debug").config().getEngine();

        assertThat(engine.isShowProcessed()).isTrue();
        assertThat(engine.isShowSkipped()).isTrue();
    }

    private static FacepalmCLI parse(final String... args) {
        final var commandLine = FacepalmCLI.commandLine();
        commandLine.parseArgs(args);
        return commandLine.getCommand();
    }

    private static Result execute(final String... args) {
        final var out = new StringWriter();
        final var err = new StringWriter();
        final var commandLine = FacepalmCLI.commandLine();
        // Plain text: picocli detects ANSI support per platform (on the Windows CI runner it colors the usage).
        commandLine.setColorScheme(CommandLine.Help.defaultColorScheme(CommandLine.Help.Ansi.OFF));
        commandLine.setOut(new PrintWriter(out, true));
        commandLine.setErr(new PrintWriter(err, true));
        final var exitCode = commandLine.execute(args);
        return new Result(exitCode, out.toString(), err.toString());
    }

    private static String mojoDefault(final String parameter) {
        final var matcher = Pattern.compile("<" + parameter + " implementation=\"[^\"]*\" default-value=\"([^\"]*)\"")
            .matcher(descriptor);
        assertThat(matcher.find()).as("No default for %s in the plugin descriptor", parameter).isTrue();
        return matcher.group(1);
    }

    /**
     * Exit code and the text picocli wrote to standard output and standard error.
     */
    private record Result(int exitCode, String out, String err) {
    }
}
