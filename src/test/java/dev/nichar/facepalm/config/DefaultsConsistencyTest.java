package dev.nichar.facepalm.config;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.util.regex.Pattern;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.Test;

/**
 * The defaults of the config classes (used by {@code FacepalmCLI}) must equal the {@code @Parameter} defaults of
 * the Maven goal, read from the generated plugin descriptor. Otherwise the same code gets different verdicts in the
 * CLI and in Maven (issue #70: errorThreshold was 70 in the CLI and 80 in Maven).
 */
class DefaultsConsistencyTest {

    /**
     * Content of the plugin descriptor generated by maven-plugin-plugin before the test phase.
     */
    private static String descriptor;

    @BeforeAll
    static void readDescriptor() throws IOException {
        try (var in = DefaultsConsistencyTest.class.getClassLoader()
            .getResourceAsStream("META-INF/maven/plugin.xml")) {
            assertNotNull(in, "plugin descriptor not generated");
            descriptor = new String(in.readAllBytes(), StandardCharsets.UTF_8);
        }
    }

    @Test
    void scoring_defaults_match_the_maven_goal() {
        final var scoring = new ScoringConfig();
        assertEquals(mojoDefault("errorThreshold"), String.valueOf(scoring.getErrorThreshold()));
        assertEquals(mojoDefault("warningThreshold"), String.valueOf(scoring.getWarningThreshold()));
        assertEquals(mojoDefault("scoringStrategy"), scoring.getStrategy().name());
        assertEquals(mojoDefault("failOnError"), String.valueOf(scoring.isFailOnError()));
        assertEquals(mojoDefault("failOnWarnings"), String.valueOf(scoring.isFailOnWarnings()));
        assertEquals(mojoDefault("showScoring"), String.valueOf(scoring.isShowScoring()));
        assertEquals(mojoDefault("showDetails"), String.valueOf(scoring.isShowDetails()));
    }

    @Test
    void engine_defaults_match_the_maven_goal() {
        final var engine = new EngineConfig();
        assertEquals(mojoDefault("maxFileSizeBytes"), String.valueOf(engine.getMaxFileSizeBytes()));
        assertEquals(mojoDefault("skipBinaryRegex"), engine.getSkipBinaryRegex());
        assertEquals(mojoDefault("showProcessed"), String.valueOf(engine.isShowProcessed()));
        assertEquals(mojoDefault("showSkipped"), String.valueOf(engine.isShowSkipped()));
    }

    private static String mojoDefault(final String parameter) {
        final var matcher = Pattern.compile("<" + parameter + " implementation=\"[^\"]*\" default-value=\"([^\"]*)\"")
            .matcher(descriptor);
        assertTrue(matcher.find(), () -> "No default for " + parameter + " in the plugin descriptor");
        return matcher.group(1);
    }
}
